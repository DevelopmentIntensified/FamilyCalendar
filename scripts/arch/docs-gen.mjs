#!/usr/bin/env node
// `npm run docs:gen` — renders docs/architecture/modules.md from registry.mjs
// so the module catalog can never drift from what the arch check enforces.
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { FOREIGN_READS, MODULES, PORT_ORDER, TABLE_OWNERS, moduleDir } from './registry.mjs';
import { ROOT } from './lib.mjs';

const rows = MODULES.map((module) => {
	const dir = moduleDir(module);
	const lower = MODULES.filter(
		(m) => m.kind === 'domain' && m.rank < (module.rank ?? Infinity)
	).map((m) => m.name);
	const mayImport =
		module.kind === 'kernel'
			? 'kernel only'
			: module.kind === 'domain'
				? ['kernel', ...lower].join(', ')
				: module.kind === 'screen'
					? 'kernel, any domain'
					: 'anything (composition root)';
	const tables = Object.entries(TABLE_OWNERS)
		.filter(([, owner]) => owner === module.name)
		.map(([table]) => table)
		.join(', ');
	const reads = Object.keys(FOREIGN_READS[module.name] ?? {}).join(', ');
	const order = PORT_ORDER.indexOf(module.name);
	const doc = existsSync(path.join(ROOT, dir, 'README.md'))
		? `[${module.name}](../../${dir}/README.md)`
		: `${module.name} (\`${dir}/\`, not ported yet)`;
	return `| ${doc} | ${module.kind}${module.parked ? ' (parked)' : ''} | ${module.rank ?? '—'} | ${order >= 0 ? order + 1 : '—'} | ${mayImport} | ${tables || '—'}${reads ? ` (reads: ${reads})` : ''} | ${module.purpose} |`;
});

const text = `# Module catalog

GENERATED by \`npm run docs:gen\` from [scripts/arch/registry.mjs](../../scripts/arch/registry.mjs). Edit the registry, not this file.

- **rank**: a domain may import only domains with a lower rank (rule R1).
- **port #**: position in the rewrite order ([LEDGER](../rewrite/LEDGER.md)).
- Modules without a link are not ported yet; their legacy files are listed in their port sheet under [docs/rewrite/modules/](../rewrite/modules/).

| module | kind | rank | port # | may import | owns tables | purpose |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`;

writeFileSync(path.join(ROOT, 'docs/architecture/modules.md'), text);
console.log('docs:gen: wrote docs/architecture/modules.md');
